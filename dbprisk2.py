def _write_installer_bat(install_dir: str) -> str:
    """
    Create/overwrite the installer .bat inside installpackages/
    so it uses the *current* QGIS the user is running.
    Returns the full path to the .bat.
    """
    qgis_prefix = QgsApplication.prefixPath()
    qgis_root = os.path.normpath(os.path.join(qgis_prefix, "..", ".."))
    bin_dir = os.path.join(qgis_root, "bin")

    python_exe = os.path.join(bin_dir, "python3.exe")
    if not os.path.exists(python_exe):
        python_exe = os.path.join(bin_dir, "python.exe")

    bat_path = os.path.join(install_dir, "py3-env.bat")  # your single .bat to keep/change
    bat = f"""@ECHO OFF
SETLOCAL ENABLEDELAYEDEXPANSION

REM Auto-generated by plugin to match the running QGIS version.
SET "OSGEO4W_ROOT={qgis_root}"
SET "QGIS_PREFIX_PATH={qgis_prefix}"
SET "PATH=%OSGEO4W_ROOT%\\bin;%PATH%"

IF EXIST "%OSGEO4W_ROOT%\\bin\\o4w_env.bat" CALL "%OSGEO4W_ROOT%\\bin\\o4w_env.bat"
IF EXIST "%OSGEO4W_ROOT%\\bin\\qt5_env.bat" CALL "%OSGEO4W_ROOT%\\bin\\qt5_env.bat"

REM Ensure QGIS libs/plugins on PATH
SET "PATH=%QGIS_PREFIX_PATH%\\bin;%PATH%"
SET "QT_PLUGIN_PATH=%QGIS_PREFIX_PATH%\\qtplugins;%QT_PLUGIN_PATH%"

REM Use Python that ships with this QGIS
SET "PYEXE={python_exe}"

REM Bootstrap pip and install from requirements.txt next to this .bat
"%PYEXE%" -m ensurepip --upgrade
"%PYEXE%" -m pip install --upgrade pip
"%PYEXE%" -m pip install -r "%~dp0requirements.txt"

ENDLOCAL
"""
    try:
        with open(bat_path, "w", encoding="utf-8") as f:
            f.write(bat)
        log(f"Installer .bat updated for this QGIS at: {bat_path}")
    except Exception as e:
        log(f"Failed to write {bat_path}: {e}", Qgis.Critical)
    return bat_path


def _run_installer_bat(install_dir: str) -> bool:
    """
    Run the installer .bat and return True if the process exit code == 0.
    """
    bat_path = _write_installer_bat(install_dir)
    try:
        proc = subprocess.run(
            ["cmd.exe", "/C", bat_path],
            check=False,
            capture_output=True,
            text=True,
            cwd=install_dir
        )
        if proc.stdout:
            log(proc.stdout)
        if proc.stderr:
            log(proc.stderr, Qgis.Warning)
        return proc.returncode == 0
    except Exception as e:
        log(f"Running installer .bat failed: {e}", Qgis.Critical)
        return False
