class _Wrap:
    def __init__(self, iface, pkg: str):
        self.iface = iface
        self.pkg = pkg
        self.mod = None
        self.inst = None

    def load(self) -> bool:
        try:
            self.mod = importlib.import_module(f".{self.pkg}", __package__)
        except Exception as e:
            log(f"Import failed for '{self.pkg}': {e}", Qgis.Critical)
            return False
        if not hasattr(self.mod, "classFactory"):
            log(f"'{self.pkg}' missing classFactory(iface)", Qgis.Critical)
            return False
        try:
            self.inst = self.mod.classFactory(self.iface)
        except Exception as e:
            log(f"classFactory() error in '{self.pkg}': {e}", Qgis.Critical)
            return False
        return True

    def init_gui(self):
        if hasattr(self.inst, "initGui"):
            try:
                self.inst.initGui()
                log(f"initGui OK: {self.pkg}")
            except Exception as e:
                log(f"initGui failed: {self.pkg}: {e}", Qgis.Critical)

    def unload(self):
        if hasattr(self.inst, "unload"):
            try:
                self.inst.unload()
                log(f"unload OK: {self.pkg}")
            except Exception as e:
                log(f"unload failed: {self.pkg}: {e}", Qgis.Critical)


class dbpRisk2Plugin:
    def __init__(self, iface):
        self.iface = iface
        self.children: List[_Wrap] = []

    def _ensure_requirements(self) -> bool:
        """
        Only prompt/install if imports are actually missing.
        Re-check after install; return True if everything importable.
        If requirements.txt is absent or unreadable, skip quietly.
        """
        install_dir = os.path.join(os.path.dirname(__file__), "installpackages")
        req_file = _requirements_file()

        missing = _missing_imports(req_file)
        if not missing:
            return True

        # Ask user for permission
        msg = QMessageBox(self.iface.mainWindow())
        msg.setIcon(QMessageBox.Question)
        msg.setWindowTitle("Install Python packages")
        msg.setText(
            "This plugin needs some Python packages that aren’t installed:\n\n"
            + "\n".join(missing)
            + f"\n\nInstall them now for the current QGIS?"
            + f"\n\n(Detected QGIS: {Qgis.QGIS_VERSION})"
        )
        msg.setStandardButtons(QMessageBox.Yes | QMessageBox.No)
        if msg.exec() != QMessageBox.Yes:
            log("User declined to install missing packages.", Qgis.Warning)
            return False

        ok = _run_installer_bat(install_dir)
        if not ok:
            QMessageBox.critical(self.iface.mainWindow(), "Installation failed",
                                 "The installer did not complete successfully. See QGIS Logs for details.")
            return False

        missing_after = _missing_imports(req_file)
        if not missing_after:
            QMessageBox.information(self.iface.mainWindow(), "Packages installed",
                                    "Required packages were installed successfully.\n"
                                    "If anything still fails to import, please restart QGIS.")
            return True

        QMessageBox.critical(self.iface.mainWindow(), "Packages still missing",
                             "Some packages still could not be imported after installation:\n\n"
                             + "\n".join(missing_after)
                             + "\n\nPlease check the QGIS Logs for details.")
        return False

    def initGui(self):
        self._ensure_requirements()

        for name in SUBPLUGINS:
            w = _Wrap(self.iface, name)
            if w.load():
                self.children.append(w)
                w.init_gui()
            else:
                log(f"Skipped '{name}' due to load error", Qgis.Warning)

    def unload(self):
        for w in reversed(self.children):
            w.unload()
        self.children.clear()
