PLUGIN_TAG = "dbpRisk"

def log(msg, lvl=Qgis.Info):
    QgsMessageLog.logMessage(str(msg), PLUGIN_TAG, lvl)

SUBPLUGINS = ["dbpriskapp", "dbpSimulatorUI"]

_REQ_LINE = re.compile(r"^\s*([A-Za-z0-9._-]+)(?:\[.*?\])?\s*([<>=!~]=?.*)?$")

def _requirements_file() -> str:
    """Absolute path to installpackages/requirements.txt (next to this file)."""
    install_dir = os.path.join(os.path.dirname(__file__), "installpackages")
    return os.path.join(install_dir, "requirements.txt")

def _parse_requirement_names(req_file: str):
    """
    Return just the distribution names (no versions).
    If the file is missing or unreadable, return [] silently (no warnings).
    """
    try:
        if not os.path.isfile(req_file):
            return []
        names = []
        with open(req_file, "r", encoding="utf-8", errors="ignore") as f:
            for raw in f:
                s = raw.strip()
                if not s or s.startswith("#"):
                    continue
                # Skip direct URLs or local wheels
                if s.startswith(("http://", "https://")) or s.endswith((".whl", ".zip", ".tar.gz")):
                    if "#egg=" in s:  # best-effort
                        names.append(s.split("#egg=", 1)[1])
                    continue
                m = _REQ_LINE.match(s)
                if m:
                    names.append(m.group(1))
        return names
    except Exception:
        # Silent skip on any error
        return []

def _missing_imports(req_file: str):
    """
    Try importing modules for each requirement (dash->underscore). If import fails, mark missing.
    Version specs are ignored; installer handles versions.
    """
    missing = []
    for dist in _parse_requirement_names(req_file):
        modname = dist.replace("-", "_")
        try:
            importlib.import_module(modname)
        except Exception:
            missing.append(dist)
    return missing
